  'M2 element positions n + delta_n, delta_n ~ N(0, sigma^2) half-wavelengths, sigma in {0.02,0.05,0.1,0.2}, both arrays; M3 per-antenna phase U(+-20/30/45 deg), '
  'gain U(+-6 dB), phase 30 deg + gain 4 dB (the existing model, outside the CNN training range of 8 deg / 3 dB); M4 phase shifters of b in {4,3,2,1} bits '
